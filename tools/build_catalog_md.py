#!/usr/bin/env python3
"""Regenerate catalog/CATALOG.md and lint summaries from catalog/*.json."""
import json, pathlib, sys, collections
ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
from c3d_lint import lint
cat = json.load(open(ROOT / 'catalog/forum-threads.json'))
tg = json.load(open(ROOT / 'catalog/tres-graficos.json'))
for t in cat:
    for s in t['scripts']:
        typ, issues = lint(ROOT / t['scripts_dir'] / s['file'])
        s['lint'] = {'errors': [m for l, _, m in issues if l == 'ERROR'], 'warnings': [m for l, _, m in issues if l == 'WARN']}
json.dump(cat, open(ROOT / 'catalog/forum-threads.json', 'w'), indent=1, ensure_ascii=False)
ICON = {'reported-working': '✅ works', 'fixed-later': '🔧 fixed', 'mixed': '⚠️ mixed', 'reported-broken': '❌ broken',
        'author-only': '· no feedback', 'superseded': '↪ superseded', 'discussion': '💬 discussion', 'request-only': '❓ request'}
rows = collections.defaultdict(list)
for t in cat:
    r = t.get('review')
    if not r: continue
    best = r.get('best_file')
    lnk = f"[{best}](../{t['scripts_dir']}/{best.replace(' ', '%20')})" if best else ('external' if r.get('hosted_externally') else '—')
    errs = sum(len(s['lint']['errors']) for s in t['scripts'] if s['file'] == best) if best else 0
    rows[r['category']].append((t['last'] or '', f"| [{t['title'].replace('|','/')}]({t['url']}) | {t['author']} | {t['start'][:4]}–{(t['last'] or '')[:4]} | {ICON.get(r['status'], r['status'])} | {', '.join(r.get('versions_working') or []) or '—'} | {', '.join(r.get('versions_broken') or []) or '—'} | {lnk}{' ⚑'+str(errs) if errs else ''} | {r['summary'].replace('|','/')} |"))
st = collections.Counter(t['review']['status'] for t in cat if t.get('review'))
L = ['# Cheetah3D Script Catalog', '',
     f"{len(cat)} threads from the Cheetah3D forum's *Scripting* section (Script downloads + General), {sum(len(t['scripts']) for t in cat)} archived script files, plus {len(tg)} entries from tg_jp's site (tres-graficos.jp). Generated by `tools/build_catalog_md.py`.", '',
     '**Status** is what forum posters reported — not a test in 8.x. ' + ', '.join(f'{ICON[k]}: {v}' for k, v in st.most_common()) + '.', '',
     '**⚑n** = number of lint errors (`tools/c3d_lint.py`) in the best file — usually version-drift issues worth fixing before use.', '',
     'Full transcripts: `forum/threads/`. Machine-readable: `catalog/forum-threads.json` (per-thread review with evidence quotes and API lessons).', '']
for cat_name in sorted(rows):
    L += [f'## {cat_name}', '', '| Thread | Author | Active | Status | Works in | Broken in | Best file | What it does |', '|---|---|---|---|---|---|---|---|']
    L += [r for _, r in sorted(rows[cat_name], reverse=True)] + ['']
L += ['## tres-graficos.jp (tg_jp)', '', 'Scripts by tg_jp hosted on his own site, most announced in the forum (see linked thread reviews for evidence). Code is **not** archived here — download from the site.', '',
      '| Package | Date | Type(s) | Min version | Forum threads | Description |', '|---|---|---|---|---|---|']
for e in sorted(tg, key=lambda e: -(int(e['date']) if e['date'] else 0)):
    desc = ' '.join(e['description'].split())[:160].replace('|', '/')
    L.append(f"| [{e['package']}]({e['url']}) | {e['date'] or '—'} | {', '.join(sorted({s['type'] for s in e['scripts']})) or '—'} | {', '.join(e['stated_min_version']) or '—'} | {' '.join(f'[#{i}](https://www.cheetah3d.com/forum/index.php?threads/{i}/)' for i in e['forum_threads']) or '—'} | {desc} |")
(ROOT / 'catalog/CATALOG.md').write_text('\n'.join(L) + '\n')
print('ok', sum(len(v) for v in rows.values()))
